import { randomBytes, scrypt, timingSafeEqual, createHash } from "node:crypto";

/** scrypt parameters (OWASP-acceptable: N=2^15, r=8, p=1). Stored with the hash so they can be raised later. */
const N = 32768;
const R = 8;
const P = 1;
const KEYLEN = 64;

function derive(password: string, salt: Buffer, n: number, r: number, p: number): Promise<Buffer> {
  return new Promise((resolve, reject) =>
    scrypt(password.normalize("NFKC"), salt, KEYLEN, { N: n, r, p, maxmem: 128 * n * r * 2 }, (err, key) => (err ? reject(err) : resolve(key))),
  );
}

export async function hashPassword(password: string): Promise<string> {
  const salt = randomBytes(16);
  const key = await derive(password, salt, N, R, P);
  return `scrypt$${N}$${R}$${P}$${salt.toString("base64url")}$${key.toString("base64url")}`;
}

export async function verifyPassword(password: string, stored: string): Promise<boolean> {
  const parts = stored.split("$");
  if (parts.length !== 6 || parts[0] !== "scrypt") return false;
  const [, n, r, p, salt, hash] = parts;
  const expected = Buffer.from(hash, "base64url");
  const key = await derive(password, Buffer.from(salt, "base64url"), Number(n), Number(r), Number(p));
  return key.length === expected.length && timingSafeEqual(key, expected);
}

/** Same-cost dummy check so unknown emails take as long as wrong passwords (no account enumeration by timing). */
let dummy: string | undefined;
export async function burnPasswordCheck(password: string): Promise<void> {
  dummy ??= await hashPassword("valta-dummy-password");
  await verifyPassword(password, dummy);
}

/** Random opaque token for cookies / reset links, and the hash we store instead of it. */
export function newToken(): string {
  return randomBytes(32).toString("base64url");
}

export function hashToken(token: string): string {
  return createHash("sha256").update(token).digest("hex");
}
